#!/usr/bin/env python3
# gen_dispatch.py - generate src/fd2_dispatch.c (de-guest phase C2).
#
# fd2_globals.h exposes the seven game dispatch tables as 4-byte function
# pointer cells inside the LE data mirror.  On a 64-bit host each pointer view
# reads/writes 8 bytes over 4-byte-spaced cells, so the tables are wrong.  This
# tool emits real host arrays of function pointers initialised from
# analysis/dispatch_tables.csv, resolving each target through the restored
# manifest and src/include/fd2_aliases.h.
#
# Run from the repository root:  python3 tools/gen_dispatch.py
import csv, re, collections, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AN = os.path.join(ROOT, 'analysis')

# True table lengths (first NOTCODE/ZERO slot ends the table; see PROGRESS 0-D).
LEN = {
    'funcs_1197B': 30, 'funcs_1199C': 90, 'funcs_1541F': 28,
    'funcs_25E23': 30, 'funcs_25E3A': 30, 'funcs_30469': 10, 'funcs_37012': 10,
}


def load_alias():
    alias = {}
    for name in ('fd2_aliases.h', 'fd2_restored_aliases.h'):
        p = os.path.join(ROOT, 'src', 'include', name)
        if not os.path.exists(p):
            continue
        for line in open(p, encoding='utf-8'):
            m = re.match(r'#define\s+(sub_[0-9A-Fa-f]+)\s+(\w+)', line)
            if m:
                alias[m.group(1)] = m.group(2)
    return alias


def main():
    alias = load_alias()
    rows = list(csv.DictReader(open(os.path.join(AN, 'dispatch_tables.csv'),
                                    encoding='utf-8')))
    tabs = collections.defaultdict(dict)
    for r in rows:
        tabs[r['table']][int(r['index'])] = r

    out = [
        '/* fd2_dispatch.c - GENERATED by tools/gen_dispatch.py - do not edit.',
        ' *',
        ' * Native (de-guest phase C2) replacements for the seven game dispatch',
        ' * tables that fd2_globals.h used to expose as 4-byte function-pointer',
        ' * cells inside the LE data mirror.  Each table is now a real array of',
        ' * host function pointers, initialised from analysis/dispatch_tables.csv',
        ' * (target -> restored C symbol via src/include/fd2_aliases.h).',
        ' *',
        ' * Hybrid profile (FD2_GUEST_FIXED) keeps the loader-relocated mirror cells.',
        ' */',
        '#include "game/fd2_game.h"',
        '',
        '#ifndef FD2_GUEST_FIXED',
    ]
    for t, n in LEN.items():
        ent = tabs[t]
        terms = []
        for i in range(n):
            r = ent.get(i)
            if r is None:
                terms.append('0')
                continue
            nm = alias.get(r['target_name'], r['target_name'])
            terms.append('(void (*)(void))' + nm)
        out.append('void (*funcs_%s[%d])(void) = {' % (t.split('_')[1], n))
        for i in range(0, n, 5):
            out.append('    ' + ', '.join(terms[i:i + 5]) + ',')
        out.append('};')
        out.append('')
    out.append('#endif /* !FD2_GUEST_FIXED */')
    open(os.path.join(ROOT, 'src', 'fd2_dispatch.c'), 'w',
         encoding='utf-8').write('\n'.join(out) + '\n')
    print('wrote src/fd2_dispatch.c')


if __name__ == '__main__':
    main()
